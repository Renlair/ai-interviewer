package main

import "strings"

// stage 是面试的一个阶段。阶段由后端按规则推进，模型只负责评估和提问。
type stage struct {
	Name     string
	Goal     string
	EndMin   int // 面试进行到这一分钟仍在本阶段，就进入下一阶段
	MaxTurns int // 候选人在本阶段最多回答几轮
}

// flow 是一个面试方向的完整流程：从哪里开场，经过哪些阶段。
type flow struct {
	Opening string  // 开场从哪里切入
	Stages  []stage // 最后两个阶段固定是反问、收尾
}

func (f flow) closing() int { return len(f.Stages) - 1 }

// stageAt 返回第 i 个阶段，越界时取最近的合法阶段。
func (f flow) stageAt(i int) stage { return f.Stages[min(max(i, 0), f.closing())] }

func (f flow) names() string {
	var names []string
	for _, s := range f.Stages {
		names = append(names, s.Name)
	}
	return strings.Join(names, "、")
}

// newFlow 拼出一个方向的流程：开场 + 三个方向专属阶段 + 反问、收尾。时间按 30 分钟分配。
func newFlow(opening, introGoal string, middle [3][2]string) flow {
	return flow{
		Opening: opening,
		Stages: []stage{
			{"开场", introGoal + "顺带了解候选人的背景和想去的岗位，不要让候选人做正式的自我介绍。", 4, 3},
			{middle[0][0], middle[0][1], 13, 6},
			{middle[1][0], middle[1][1], 21, 6},
			{middle[2][0], middle[2][1], 27, 4},
			{"反问", "问候选人有没有想问你的，简短真诚地回答。", 29, 3},
			{"收尾", "感谢候选人，告诉他稍后可以查看复盘。", 0, 0},
		},
	}
}

